   <h3>A complete solution for all your medical image viewing needs</h3> 
<p>Telerad Viewer is a zero-footprint, HTML5-based, cross platform, BYOD (bring your own device)
regulation compliant web based DICOM viewing solution which can be implemented in local
network as well as over cloud server. It offers full DICOM compliance and support for a wide variety
of devices, including desktop, computers, tablets and smartphones.</p>

<h3>Works on desktops, tablets, smartphones </h3>
<p>TELERAD ViEWER is compatibile with Windows, Mac OS X and Linux desktop clients, on any
HTML5-capable platform, including last generation web browsers, Android tablets and
smartphones, Apple’s iPads and iPhones. You may clinically review any of your dicom images from
any of your devices using TELERAD ViEWER.</p>

<h3>Accessing DICOM images through the LAN or through the Internet</h3>
<p>The architecture of TELERAD ViEWER is fully web-based. With the appropriate permissions, users are
able to access to DICOM viewing functionalities wherever they are, both from within the hospital’s
or medical center’s DICOM network, and from remote locations. No matter the particular client
computer or device being used, it is always possible to load the viewer and view medical images. The
web-based architecture has also many benefits in terms of ease of software maintenance: software
updates are applied to the server, and they automatically propagated to all clients.</p>

<h3>Robust, reliable, supported, certified</h3>
<p>TELERAD ViEWER has more than 10 years of experience in the medical imaging and DICOM domain.
Over all these years, TELERAD ViEWER has been continuously improved and enriched with new
functionalities. Choosing TELERAD ViEWER means choosing a robust, highly-reliable, hassle-free,
professionally-supported, regulations-compliant DICOM viewing solution.</p>

<h3>Technical Features – basic</h3>
<ul>
<li>•	Runs on any HTML5-capable device, including Apple iOS and Android tablets or smartphones, as well as last-generation desktop web browsers. 
<li>•	Can display virtually all kinds and encodings of DICOM image files. </li>
<li>•	Supports searches on studies.</li>
<li>•	Configurable and flexible display layout for images.</li>
<li>•	Interactive image stacking, window/level and zoom.</li> 
<li>•	Reference lines. </li>
<li>•	Distance and area measurement tools.</li> 
<li>•	Supports cine-playback of multi-frame sequences. </li>
<li>•	Runs on standard hardware. </li>
<li>•	Supports Stream based lossless compression schemes.
</li>    
</ul>

<h3>Technical Features – advanced</h3>
<ul>
<li>•	Supports window/level, zoom, rotation, flipping, pseudo-coloring, enhancement filters on images.</li>
<li>•	 Distance, area, angle and density measurement tools, plus several graphical annotation tools.</li> 
<li>•	Hanging Protocols. </li>
<li>•	Support for Echo Stress studies. </li>
<li>•	Multi-planar reconstruction (MPR), both orthogonal and oblique. </li>
<li>•	Reference lines (scout lines) and 3D localizer cursor for MR and CT studies. </li>
<li>•	Reporting functions: support for DICOM Structured Reports (SR), plain text reports, voice reports. </li>
<li>•	Export images in DICOM (incl. PS and KI), JPG, PNG, JPEG-2000 and AVI formats to server and local.</li> 
<li>•	DICOM CD/DVD production functions, with embedded cross-platform auto-running viewer(LocalEye Viewer).</li>
<li>•	DICOM anonymization features on DICOM export and DICOM CD/DVD production. </li>
<li>•	Supports multi-monitor configurations.</li>

</ul>
                 
                    

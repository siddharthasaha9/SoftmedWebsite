    $(".rl").hide();
    $(".text_over").css({"height":"118px","-webkit-line-clamp":"5"});
    $("#text_over"+per).css({"height":"auto","-webkit-line-clamp":"25"});
    $("#rm"+per).hide();
    $("#rl"+per).show();
}

function rl_open(per){
    $("#text_over"+per).css({"height":"118px","-webkit-line-clamp":"5"});
    $("#rl"+per).hide();
    $("#rm"+per).show();
}

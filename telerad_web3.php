                    <h3>Are you looking for an easy reporting solution? </h3>
<p>TELERAD WEB PORTAL (TWP) is an end to end cross platform, BYOD(Bring your own device),
regulation compliant web based teleradiology reporting solution. It is our Remote Diagnostics
Management Service –<br>
the only fully managed cloud based innovative Teleradiology service platform leveraging different
forms of technologies (PACS, DICOM) to provide end-to-end solution for remote radiology reporting
through which we make it possible for certified and experienced radiologists to extend their reach
to otherwise unreachable patients and provide cost effective radio-diagnosis.</p>

<p>TWP can be implemented in wide area network as well as on cloud server. TWP is backed up by our
robust PACS Server – Telerad PACS Server on cloud network at the back end for smooth flow of
DICOM studies from different remote centres. The backend server supports all types of DICOM
studies. The highly responsive web enabled user interface of TWP is very easy to understand and
operate; both – the Radiologist at the reporting end and the user at the remote end are always at
sync. TELERAD WEB PORTAL also comes with a cross platform web enabled DICOM viewer named
TELERAD ViEWER which supports all the major tools for image analysis. TWP can provide access to
multiple user types simultaneously. Individual centres can be mapped to individual radiologists, and
different such other combinations are possible. Mapping of centres to reporting clients and vice
versa is a matter of configuration in TWP. Overall, TWP provides you the flexibility of radiology
reporting over WAN/Internet/IP-VPN.</p>

<h3>Accessing medical report through the Internet</h3>
<p>The architecture of TELERAD WEB PORTAL is fully web-based. With proper authentication, users are
able to access their account from any location. No matter the particular client computer or device
being used, it is always possible to access TWP. The web-based architecture has also many benefits
in terms of ease of software maintenance: software updates are applied to the server, and they
automatically propagate to all clients.</p>

<h3>Works on desktops, tablets, smartphones </h3>
<p>TELERAD WEB PORTAL is equipped with software modules for clinical review of radiology studies on
desktops, tablets and smartphones. This portal is a zero-footprint, HTML5-based, cross-device, fast
and easy-to-use platform for all your teleradiology needs. It is compatible with Windows, Mac OS X
and Linux desktop clients, on any HTML5-capable platform, including last generation web browsers,
Android tablets and smartphones, Apple’s iPads and iPhones.</p>

<h3>Multiple report operation for single study</h3>
<p>TWP allows radiologists to create more than one report for a single study, if required (Authorized
users only). The dashboard easily indicates presence of multiple reports for a particular study. User
at the remote centre end can easily swap between the reports, in case of multiple reports and can
take direct print from the same window.</p>

<h3>Rich text Editor for Reporting & Patient History </h3>
<p>TWP equips both ends - the reporting doctor and the radiology technician at the remote centre with
a rich text editor which gives them the ease of writing on a MS Word type environment. The editor
allows all the major features of a text editor.</p>

<h3>Template based Reporting </h3>
<p>TWP has a strong reporting engine at the back end, which can store n number of reporting
templates per reporting user. The system also provides option for the Reporting doctors to create
their own templates for different type of studies ( eg: X-Ray Chest PA View, CT Scan Whole Body,
MRI of Spine etc )</p>

<h3>Search your studies with multiple criteria </h3>
<p>TWP supports binomial search. You can search your desired study / list of studies by different
combinations (eg1: All CR studies between 1Jan2014 – 12 Jan2014 coming from remote centre ABC;
eg2: List all un-reported studies a on date.</p>

<h3>Automated updation of Status Information </h3>
<p>The portal auto refreshes and updates the status of any reported studies automatically. Doctors can
also understand from the dashboard interface whether medical history or patient notes have been
transferred or the prepared report has been printed. The system also supports auto email and auto
sms as plug-ins for real-time status of study upload and completion of report to radiologists and
corresponding centre.</p>

<h3>Digitally sign your Reports</h3>
<p>With TELERAD WEB PORTAL a radiologist can attach his/her digital signature to the radiology report
that he finalizes. The signatures along with registration nos, degrees, etc are safely stored in the
database and are mapped to user login information. Provision of counter signing is also present.</p>

<h3>Robust, reliable, supported </h3>
<p>TELERAD WEB PORTAL is enriched with new user centric features &amp; functionalities. Choosing
TELERAD WEB PORTAL means choosing a robust, highly-reliable, hassle-free, professionally-
supported, regulations-compliant teleradiology reporting solution.</p>

<p><strong>Our Teleradiology reporting services platform has two types of subscription plans. You can sign up
per report basis or at a one-time charge. The other type of sign up is on a &#39;per study basis&#39;</strong></p>


                   <h3 class="" style="margin-top:15px;">The Background</h3> 
<p>With heart attacks being reported as the reason for the death of one Indian every 33
seconds, cardiac health has emerged as a chief concern in the country and have become the
leading cause of mortality in India. For heart monitoring purposes, in an emergency
situation, an ECG test should be done within the golden hour, but in India, it often takes
about 6–8 hours. More than half a million people die of heart attacks each year because of a
lack of immediate medical attention. But, there is a huge shortage in the availability of
trained human resources for health care in India. The shortage of a trained workforce is
observed at all levels of health care, including specialists, primary care physicians, and
frontline health workers. Innovative methods needed to be developed and tested in Indian
settings to overcome these challenges, approaches that could potentially improve the
efficiency of care. Incorporating information and communication technology tools, and task-
shifting and task-sharing strategies was the solution.</p>

      
